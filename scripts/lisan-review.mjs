// Writes LISAN-REVIEW.md: every Lisan ud-Dawat line in the app, for proofreading.
// Run: node --experimental-strip-types scripts/lisan-review.mjs
import { writeFileSync } from "node:fs";
import { SEED } from "../worker/seed.ts";
import { STRINGS, STRINGS2 } from "../src/i18n.ts";

const cell = (s) => String(s ?? "").replace(/\n/g, "<br>").replace(/\|/g, "\\|");
let out = `# Lisan ud-Dawat review

Every Lisan ud-Dawat line in the app. Nothing in parts 1 and 2 is shown to zaereen until you approve it
in admin (Lisan review tab); until then a zair who picks Lisan ud-Dawat sees the English line.
Approve or correct each line in admin: that is the source of truth, this file is only the checklist.
Generated by \`scripts/lisan-review.mjs\`; do not edit by hand.

Things I was unsure of are listed at the end.

## 1. Transcribed from your slides (wording already approved; check my transcription)

| Where | Slide | English | Lisan ud-Dawat |
|---|---|---|---|
`;
const rows = SEED.filter((s) => Object.values(s.lud ?? {}).some((v) => v?.trim()));
const fromSlide = rows.filter((s) => s.data?.source);
for (const s of fromSlide) for (const [f, v] of Object.entries(s.lud)) if (v?.trim()) out += `| \`${s.id}\` ${f} | ${s.data.source.replace("content-source/", "")} | ${cell(s.en?.[f])} | ${cell(v)} |\n`;

out += `\n## 2. Written by Claude from the English (needs your proofread)\n\n| Where | English | Lisan ud-Dawat |\n|---|---|---|\n`;
for (const s of rows.filter((s) => !s.data?.source)) for (const [f, v] of Object.entries(s.lud)) if (v?.trim()) out += `| \`${s.id}\` ${f} | ${cell(s.en?.[f])} | ${cell(v)} |\n`;

out += `\n## 3. Words of the app itself (buttons, tab names)\n\nThese are in the code (\`src/i18n.ts\`), not in admin, and are live now in Lisan ud-Dawat mode. Tell me any corrections.\n\n| Key | English | Lisan ud-Dawat |\n|---|---|---|\n`;
for (const [k, [en, lud]] of [...Object.entries(STRINGS), ...Object.entries(STRINGS2)]) out += `| ${k} | ${cell(en)} | ${cell(lud)} |\n`;

out += `
## Points I was unsure of

- Slides write \`نه\` / \`يه\`; the house style writes \`نھ\` / \`يھ\`. I used the house style.
- Slide 04 and 05 show a small ج after "ما" and "نے"; I wrote it as \`}\` (the Kanz al-Marjaan small-jeem mark).
- Slide 07: I read the last words as "جهگڑو نئي كروو". Please check "جهگڑو" and "نئي".
- Slide 10: "پهلے دن" is written with the house ligature as "پظظلے دن".
- "Nashta" is written "ناشتا", "Ohbat" as "اهبة", "mas'ool" as "مسئول".
- Clock times stay in Latin digits ("8:00 am") in both languages, as on the Mannat Niyaz slide.
- English words stay in Latin letters inside Lisan lines (Room, Reception, Wi-Fi, group leader), as on the Izan cards slide.
`;
writeFileSync(new URL("../LISAN-REVIEW.md", import.meta.url), out);
console.log("LISAN-REVIEW.md written:", rows.length, "items");
